interface MilestoneSeed extends Omit<MilestoneDefinition, 'checklist'> {
  checklist: string[];
}

function milestone(seed: MilestoneSeed): MilestoneDefinition {
  return {
    ...seed,
    checklist: seed.checklist.map((label, index) => ({ id: `${seed.id}-c${index + 1}`, label })),
  };
}

